/**
 * Get daily verse deterministically by day of year
 */
export function getDailyVerse(targetDate?: Date): BibleVerse {
  const d = targetDate || new Date();
  const startOfYear = new Date(d.getFullYear(), 0, 0);
  const diff = d.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  
  const index = Math.abs(dayOfYear) % BIBLE_MEMORY_VERSES.length;
  return BIBLE_MEMORY_VERSES[index];
}

/**
 * Find verse by exact or partial reference query (e.g. "John 1:5-7", "John 1:5", "john 3:16", "约翰福音 1:5")
 */
export function findVerseInDatabase(query: string): BibleVerse | undefined {
  const clean = query.trim().toLowerCase().replace(/\s+/g, ' ');
  return BIBLE_MEMORY_VERSES.find(v => {
    const refEn = v.referenceEn.toLowerCase();
    const refZh = v.referenceZh.toLowerCase();
    const id = v.id.toLowerCase();
    return (
      refEn === clean ||
      refZh === clean ||
      id === clean ||
      refEn.replace(/\s+/g, '') === clean.replace(/\s+/g, '') ||
      refZh.replace(/\s+/g, '') === clean.replace(/\s+/g, '')
    );
  });
}
